// =============================================================
// CURRENT LESSON STATE
// =============================================================

let selectedGrade = null;
let selectedCategory = null;
let selectedLesson = null;

let currentQuestion = 0;
let score = 0;


// =============================================================
// PAGE CONTROL
// =============================================================

function hideAllPages() {

    document.querySelectorAll(".page").forEach(page => {
        page.classList.add("hidden");
    });

}


function showHome() {

    hideAllPages();

    document
        .getElementById("home")
        .classList.remove("hidden");

}


// =============================================================
// GRADE SELECTION
// =============================================================

function showCategories(grade) {

    selectedGrade = grade;

    hideAllPages();

    const page = document.getElementById("categories");

    page.classList.remove("hidden");

    document.getElementById("category-title").textContent =
        `${grade.name} Math`;

    const container =
        document.getElementById("category-list");

    container.innerHTML = "";

    grade.categories.forEach(category => {

        const button = document.createElement("button");

        button.className = "card";

        button.textContent = category.name;

        button.onclick = () => {
            showLessons(category);
        };

        container.appendChild(button);

    });

}


// =============================================================
// CATEGORY SELECTION
// =============================================================

function showLessons(category) {

    selectedCategory = category;

    hideAllPages();

    const page = document.getElementById("lessons");

    page.classList.remove("hidden");

    document.getElementById("lesson-title").textContent =
        category.name;

    const container =
        document.getElementById("lesson-list");

    container.innerHTML = "";

    category.lessons.forEach(lesson => {

        const button = document.createElement("button");

        button.className = "lesson-button";

        button.textContent =
            `Lesson ${lesson.number}: ${lesson.title}`;

        button.onclick = () => {
            startLesson(lesson);
        };

        container.appendChild(button);

    });

}


// =============================================================
// START LESSON
// =============================================================

function startLesson(lesson) {

    selectedLesson = lesson;

    currentQuestion = 0;

    score = 0;

    hideAllPages();

    document
        .getElementById("lesson-page")
        .classList.remove("hidden");


    document.getElementById("lesson-page-title").textContent =
        `Lesson ${lesson.number}: ${lesson.title}`;


    document.getElementById("lesson-explanation").textContent =
        lesson.explanation;


    document
        .getElementById("completion")
        .classList.add("hidden");


    document
        .getElementById("practice")
        .classList.remove("hidden");


    showQuestion();

}


// =============================================================
// SHOW QUESTION
// =============================================================

function showQuestion() {

    const question =
        selectedLesson.questions[currentQuestion];


    document.getElementById("question-number").textContent =
        `Question ${currentQuestion + 1} of ${selectedLesson.questions.length}`;


    document.getElementById("question-text").textContent =
        question.question;


    const input =
        document.getElementById("answer-input");


    input.value = "";

    input.disabled = false;

    input.focus();


    const feedback =
        document.getElementById("feedback");


    feedback.textContent = "";

    feedback.className = "";


    document.getElementById("check-button").disabled = false;

}


// =============================================================
// CHECK ANSWER
// =============================================================

function checkAnswer() {

    const input =
        document.getElementById("answer-input");

    const feedback =
        document.getElementById("feedback");

    const button =
        document.getElementById("check-button");


    const userAnswer =
        input.value.trim().toLowerCase();


    const correctAnswer =
        String(
            selectedLesson.questions[currentQuestion].answer
        )
        .trim()
        .toLowerCase();


    // Don't allow empty answers

    if (userAnswer === "") {

        feedback.textContent =
            "⚠️ Enter an answer first!";

        feedback.className = "wrong";

        return;

    }


    button.disabled = true;

    input.disabled = true;


    // CORRECT

    if (userAnswer === correctAnswer) {

        score++;

        feedback.textContent =
            "✅ Correct!";

        feedback.className = "correct";

    }

    // WRONG

    else {

        feedback.textContent =
            `❌ Not quite! The correct answer is ${selectedLesson.questions[currentQuestion].answer}.`;

        feedback.className = "wrong";

    }


    // Move to next question

    setTimeout(() => {

        currentQuestion++;


        if (
            currentQuestion <
            selectedLesson.questions.length
        ) {

            showQuestion();

        }

        else {

            finishLesson();

        }

    }, 1500);

}


// =============================================================
// FINISH LESSON
// =============================================================

function finishLesson() {

    document
        .getElementById("practice")
        .classList.add("hidden");


    document
        .getElementById("completion")
        .classList.remove("hidden");


    document.getElementById("score").textContent =
        `You scored ${score} out of ${selectedLesson.questions.length}!`;


    const result =
        document.getElementById("result-message");


    if (
        score ===
        selectedLesson.questions.length
    ) {

        result.textContent =
            "🏆 Perfect score! You crushed it!";

    }

    else if (score >= 3) {

        result.textContent =
            "👍 Nice work! Keep practicing and you'll get even stronger.";

    }

    else {

        result.textContent =
            "📚 Keep practicing! Try the lesson again and see if you can improve your score.";

    }

}


// =============================================================
// LOAD GRADES
// =============================================================

function loadGrades() {

    const container =
        document.getElementById("grade-list");


    container.innerHTML = "";


    grades.forEach(grade => {

        const button =
            document.createElement("button");


        button.className = "card";

        button.textContent = grade.name;


        button.onclick = () => {
            showCategories(grade);
        };


        container.appendChild(button);

    });

}


// =============================================================
// START WEBSITE
// =============================================================

document.addEventListener(
    "DOMContentLoaded",
    () => {

        loadGrades();


        document
            .getElementById("check-button")
            .addEventListener(
                "click",
                checkAnswer
            );


        document
            .getElementById("answer-input")
            .addEventListener(
                "keydown",
                event => {

                    if (event.key === "Enter") {

                        checkAnswer();

                    }

                }
            );

    }
);
